"""The inventory of record: every behaviour the suite claims to cover.

This is deliberately plain data in Python rather than a YAML fixture: there is
no fixture directory to lose, no generated artefact to regenerate, and a missing
entry is a failing test rather than a silent skip.

Each case names the section it belongs to and whether it is a positive case
(the documented behaviour happens) or a negative case (the failure is reported
in the documented way). ``test_inventory.py`` cross-checks this list against the
``CASES`` mapping declared by each test module.

A case id is a promise, not a label: when behaviour changes, change the case --
in the inventory, in the same commit -- rather than renaming it to match.
"""

